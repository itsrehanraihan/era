//! UI IR -> Kotlin + Jetpack Compose source.
//!
//! The generated code uses only common Compose APIs (foundation, ui), so the
//! same files compile for the desktop preview (Compose Multiplatform) and for
//! Android. Images, icons and fonts are loaded through three host functions
//! that each platform implements: `eraImage(path)`, `eraIcon(path)` and
//! `eraFontFamily(files)` (see `platforms/`). Output is deterministic.

pub mod android;
mod draw;
pub mod kotlin;
mod runtime;
mod screens;
mod stores;
pub mod svg;
mod theme;

use era_ir::ir::App;

/// Generated source files, relative to the Kotlin source root.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Output {
    /// Kotlin package, `<app id>.ui`.
    pub package: String,
    /// `(relative path, contents)`, sorted by path.
    pub files: Vec<(String, String)>,
}

pub const GENERATED_HEADER: &str =
    "// Generated by ERA. Do not edit: changes are overwritten on the next build.\n";

pub fn package_for(app: &App) -> String {
    format!("{}.ui", app.id)
}

/// Code generation options.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct Options {
    /// `era export`: code the team owns. Files say so instead of "do not
    /// edit", and comments name elements without internal IR ids.
    pub export: bool,
}

/// Header for exported files: ordinary code the team owns.
pub const EXPORT_HEADER: &str =
    "// Generated by ERA (era export). This is ordinary Kotlin: edit it freely.\n";

/// Rewrite the build-mode "do not edit" headers of generated Android
/// resources and helper files into export headers (`era export`).
pub fn export_text(text: &str) -> String {
    text.replace(GENERATED_HEADER, EXPORT_HEADER)
        .replace(
            "<!-- Generated by ERA. Do not edit. -->",
            "<!-- Generated by ERA (era export). Edit freely. -->",
        )
        .replace(
            "<!-- Generated by ERA from SVG. Do not edit. -->",
            "<!-- Generated by ERA from SVG (era export). Edit freely. -->",
        )
}

pub fn generate(app: &App) -> Output {
    generate_with(app, Options::default())
}

pub fn generate_with(app: &App, options: Options) -> Output {
    let mut out = generate_inner(app, options);
    if options.export {
        for (_, text) in &mut out.files {
            *text = text.replacen(GENERATED_HEADER, EXPORT_HEADER, 1);
        }
    }
    out
}

fn generate_inner(app: &App, options: Options) -> Output {
    let package = package_for(app);
    let dir = package.replace('.', "/");
    let mut files = vec![
        (format!("{dir}/EraTheme.kt"), theme::generate(app, &package)),
        (format!("{dir}/EraRuntime.kt"), runtime::generate(&package)),
        (format!("{dir}/EraDraw.kt"), draw::generate(&package)),
        (
            format!("{dir}/EraScreens.kt"),
            screens::registry(app, &package),
        ),
    ];
    if let Some(stores) = stores::generate(app, &package) {
        files.push((format!("{dir}/EraStores.kt"), stores));
    }
    for s in &app.screens {
        files.push((
            format!("{dir}/screens/{}Screen.kt", s.name),
            screens::screen(s, &package, options.export),
        ));
    }
    files.sort();
    Output { package, files }
}
