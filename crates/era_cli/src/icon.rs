//! Launcher icons from `app { icon: "Images/app_icon.png" }` (D-085).
//!
//! Writes, for each screen density:
//! - `mipmap-*/ic_launcher.png`: the legacy 48dp icon (the image on its
//!   background), used before Android 8.
//! - `mipmap-*/ic_launcher_foreground.png`: the 108dp adaptive-icon
//!   foreground, with the image fitted into the middle 72dp so launcher
//!   masks (circle, squircle) don't cut it off.
//!
//! plus `mipmap-anydpi-v26/ic_launcher.xml` and the background colour.

use std::path::Path;

use era_ir::ir::Color;
use image::{Rgba, RgbaImage, imageops};

/// `(density, pixels per 4dp)`: mdpi is 1x, xxxhdpi is 4x.
const DENSITIES: [(&str, u32); 5] = [
    ("mdpi", 4),
    ("hdpi", 6),
    ("xhdpi", 8),
    ("xxhdpi", 12),
    ("xxxhdpi", 16),
];

#[derive(Debug)]
pub struct Icons {
    pub png: Vec<(String, Vec<u8>)>,
    pub text: Vec<(String, String)>,
}

/// Draw `img` scaled to fit a `box_px` square, centred on `canvas`.
fn draw_fitted(canvas: &mut RgbaImage, img: &RgbaImage, box_px: u32) {
    let (w, h) = img.dimensions();
    let scale = f64::from(box_px) / f64::from(w.max(h));
    let nw = ((f64::from(w) * scale).round() as u32).max(1);
    let nh = ((f64::from(h) * scale).round() as u32).max(1);
    let resized = imageops::resize(img, nw, nh, imageops::FilterType::Lanczos3);
    let x = (canvas.width() - nw) / 2;
    let y = (canvas.height() - nh) / 2;
    imageops::overlay(canvas, &resized, i64::from(x), i64::from(y));
}

fn png(img: &RgbaImage) -> Result<Vec<u8>, String> {
    let mut out = std::io::Cursor::new(Vec::new());
    img.write_to(&mut out, image::ImageFormat::Png)
        .map_err(|e| e.to_string())?;
    Ok(out.into_inner())
}

pub fn launcher_icons(source: &Path, background: Option<Color>) -> Result<Icons, String> {
    let img = image::open(source)
        .map_err(|e| format!("cannot read the image: {e}"))?
        .to_rgba8();
    if img.width() < 48 || img.height() < 48 {
        return Err(format!(
            "the image is {}x{} pixels; use at least 432x432 for sharp icons",
            img.width(),
            img.height()
        ));
    }
    let bg = background.unwrap_or(Color {
        r: 255,
        g: 255,
        b: 255,
        a: 255,
    });
    let mut icons = Icons {
        png: Vec::new(),
        text: Vec::new(),
    };
    for (density, units) in DENSITIES {
        let legacy_px = 48 * units / 4;
        let mut legacy =
            RgbaImage::from_pixel(legacy_px, legacy_px, Rgba([bg.r, bg.g, bg.b, bg.a]));
        draw_fitted(&mut legacy, &img, legacy_px);
        icons.png.push((
            format!("res/mipmap-{density}/ic_launcher.png"),
            png(&legacy)?,
        ));

        let fg_px = 108 * units / 4;
        let mut foreground = RgbaImage::new(fg_px, fg_px);
        draw_fitted(&mut foreground, &img, 72 * units / 4);
        icons.png.push((
            format!("res/mipmap-{density}/ic_launcher_foreground.png"),
            png(&foreground)?,
        ));
    }
    icons.text.push((
        "res/mipmap-anydpi-v26/ic_launcher.xml".into(),
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by ERA. Do not edit. -->\n<adaptive-icon xmlns:android=\"http://schemas.android.com/apk/res/android\">\n    <background android:drawable=\"@color/ic_launcher_background\" />\n    <foreground android:drawable=\"@mipmap/ic_launcher_foreground\" />\n</adaptive-icon>\n".into(),
    ));
    icons.text.push((
        "res/values/ic_launcher_background.xml".into(),
        format!(
            "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by ERA. Do not edit. -->\n<resources>\n    <color name=\"ic_launcher_background\">#{:02X}{:02X}{:02X}{:02X}</color>\n</resources>\n",
            bg.a, bg.r, bg.g, bg.b
        ),
    ));
    Ok(icons)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn writes_every_density_and_the_adaptive_icon() {
        let dir = tempfile::tempdir().unwrap();
        let src = dir.path().join("icon.png");
        RgbaImage::from_pixel(512, 256, Rgba([255, 0, 0, 255]))
            .save(&src)
            .unwrap();
        let icons = launcher_icons(&src, None).unwrap();
        assert_eq!(icons.png.len(), 10);
        let (path, bytes) = &icons.png[9];
        assert_eq!(path, "res/mipmap-xxxhdpi/ic_launcher_foreground.png");
        let fg = image::load_from_memory(bytes).unwrap().to_rgba8();
        assert_eq!(fg.dimensions(), (432, 432));
        // Wide image: fitted into the middle 288px, transparent around it.
        assert_eq!(fg.get_pixel(216, 216).0, [255, 0, 0, 255]);
        assert_eq!(fg.get_pixel(216, 100).0[3], 0);
        assert_eq!(fg.get_pixel(10, 216).0[3], 0);
        let legacy = image::load_from_memory(&icons.png[0].1).unwrap().to_rgba8();
        assert_eq!(legacy.dimensions(), (48, 48));
        assert_eq!(legacy.get_pixel(24, 2).0, [255, 255, 255, 255]);
        assert!(icons.text[1].1.contains("#FFFFFFFF"));
        // Deterministic output.
        assert_eq!(launcher_icons(&src, None).unwrap().png, icons.png);
    }

    #[test]
    fn rejects_tiny_images() {
        let dir = tempfile::tempdir().unwrap();
        let src = dir.path().join("icon.png");
        RgbaImage::new(16, 16).save(&src).unwrap();
        assert!(launcher_icons(&src, None).unwrap_err().contains("432x432"));
    }
}
